describe("InterviewPage — session summary", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    (resumeApi.list as ReturnType<typeof vi.fn>).mockResolvedValue([]);
    (jobDescriptionApi.list as ReturnType<typeof vi.fn>).mockResolvedValue([]);
    (interviewApi.create as ReturnType<typeof vi.fn>).mockResolvedValue(MOCK_SESSION);
    (interviewApi.submitAnswer as ReturnType<typeof vi.fn>)
      .mockResolvedValueOnce(MOCK_SESSION_AFTER_ANSWER)
      .mockResolvedValueOnce(MOCK_COMPLETED_SESSION);
  });

  async function completeSession() {
    renderInterviewPage();
    await waitFor(() => screen.getByLabelText(/target role/i));
    fireEvent.change(screen.getByLabelText(/target role/i), {
      target: { value: "Backend Engineer" },
    });
    fireEvent.click(screen.getByRole("button", { name: /start practice/i }));
    await waitFor(() => screen.getByText(MOCK_QUESTIONS[0].text));

    // Answer Q1
    fireEvent.change(screen.getByRole("textbox", { name: /your answer/i }), {
      target: { value: "My answer to question one." },
    });
    fireEvent.click(screen.getByRole("button", { name: /submit/i }));
    await waitFor(() => screen.getByText(/question 2 of/i));

    // Answer Q2
    fireEvent.change(screen.getByRole("textbox", { name: /your answer/i }), {
      target: { value: "My answer to question two." },
    });
    fireEvent.click(screen.getByRole("button", { name: /submit & finish/i }));
    await waitFor(() => screen.getByText(/practice complete/i));
  }

  it("shows 'Practice complete' heading when session finishes", async () => {
    await completeSession();
    expect(screen.getByText(/practice complete/i)).toBeInTheDocument();
  });

  it("shows avg score in the summary", async () => {
    await completeSession();
    expect(screen.getByText(/avg score/i)).toBeInTheDocument();
  });

  it("shows 'Practice again' button in summary", async () => {
    await completeSession();
    expect(screen.getByRole("button", { name: /practice again/i })).toBeInTheDocument();
  });

  it("clicking 'Practice again' resets to setup form", async () => {
    await completeSession();
    fireEvent.click(screen.getByRole("button", { name: /practice again/i }));
    await waitFor(() => {
      expect(screen.getByLabelText(/target role/i)).toBeInTheDocument();
    });
  });
});

