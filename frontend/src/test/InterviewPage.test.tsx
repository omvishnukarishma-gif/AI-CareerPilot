describe("InterviewPage — Q&A flow", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    (resumeApi.list as ReturnType<typeof vi.fn>).mockResolvedValue([]);
    (jobDescriptionApi.list as ReturnType<typeof vi.fn>).mockResolvedValue([]);
    (interviewApi.create as ReturnType<typeof vi.fn>).mockResolvedValue(MOCK_SESSION);
    (interviewApi.submitAnswer as ReturnType<typeof vi.fn>).mockResolvedValue(
      MOCK_SESSION_AFTER_ANSWER
    );
  });

  async function startSession() {
    renderInterviewPage();
    await waitFor(() => screen.getByLabelText(/target role/i));
    fireEvent.change(screen.getByLabelText(/target role/i), {
      target: { value: "Backend Engineer" },
    });
    fireEvent.click(screen.getByRole("button", { name: /start practice/i }));
    await waitFor(() => screen.getByText(MOCK_QUESTIONS[0].text));
  }

  it("submit button is disabled when answer textarea is empty", async () => {
    await startSession();
    const btn = screen.getByRole("button", { name: /submit/i });
    expect(btn).toBeDisabled();
  });

  it("submit button enables after typing an answer", async () => {
    await startSession();
    fireEvent.change(screen.getByRole("textbox", { name: /your answer/i }), {
      target: { value: "Some answer text here." },
    });
    const btn = screen.getByRole("button", { name: /submit/i });
    expect(btn).not.toBeDisabled();
  });

  it("calls submitAnswer with correct payload on submit", async () => {
    await startSession();
    fireEvent.change(screen.getByRole("textbox", { name: /your answer/i }), {
      target: { value: "My detailed answer here." },
    });
    fireEvent.click(screen.getByRole("button", { name: /submit/i }));

    await waitFor(() => {
      expect(interviewApi.submitAnswer).toHaveBeenCalledWith(
        1,
        expect.objectContaining({ question_index: 0, answer: "My detailed answer here." })
      );
    });
  });

  it("moves to next question after answer submitted", async () => {
    await startSession();
    fireEvent.change(screen.getByRole("textbox", { name: /your answer/i }), {
      target: { value: "My detailed answer here." },
    });
    fireEvent.click(screen.getByRole("button", { name: /submit/i }));

    await waitFor(() => {
      expect(screen.getByText(/question 2 of/i)).toBeInTheDocument();
    });
  });
});

